class LanguageManager {
  constructor() {
    this.currentLanguage = localStorage.getItem('language') || 'en';
  }

  setLanguage(lang) {
    if (translations[lang]) {
      this.currentLanguage = lang;
      localStorage.setItem('language', lang);
      this.updatePageLanguage();
    }
  }

  getLanguage() {
    return this.currentLanguage;
  }

  t(key, defaultValue = '') {
    return translations[this.currentLanguage][key] || translations['en'][key] || defaultValue || key;
  }

  updatePageLanguage() {
    // Update HTML elements with data-i18n attributes
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translated = this.t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = translated;
      } else {
        el.textContent = translated;
      }
    });

    // Update HTML lang attribute
    document.documentElement.lang = this.currentLanguage;
    document.documentElement.dir = this.currentLanguage === 'bn' ? 'ltr' : 'ltr';

    // Dispatch custom event for other components to listen
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: this.currentLanguage } }));
  }
}

// Global instance
const i18n = new LanguageManager();

// Initialize on page load
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => {
    i18n.updatePageLanguage();
  });
} else {
  i18n.updatePageLanguage();
}
